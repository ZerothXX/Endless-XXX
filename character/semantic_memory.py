def _merge_into_memory(folder: str, char_dict: dict, source: str) -> dict:
    """把 §6.2 角色解析结果融合为 §5.1 语义记忆结构。

    - color_palette 列表前 3 项 -> main / secondary / accent
    - signature_accessories -> accessories（语义角色 / 常规用途映射）+ 原样保留
    - 所有字段都有默认值，VLM 输出缺字段不崩溃
    """
    palette = [p for p in (char_dict.get("color_palette") or [])
               if isinstance(p, str) and p.strip()]
    hair = char_dict.get("hair") or {}
    face = char_dict.get("face") or {}
    clothing = char_dict.get("clothing") or {}

    accessories = []
    for a in (char_dict.get("signature_accessories") or []):
        if not isinstance(a, dict):
            continue
        importance = str(a.get("semantic_importance", "")).lower()
        accessories.append({
            "name": a.get("name", "unknown"),
            "shape": a.get("shape", "unknown"),
            "color": a.get("color", "unknown"),
            "semantic_role": ("character identity symbol" if importance == "high"
                              else "decorative element"),
            "normal_usage": a.get("location", "unknown"),
            "description": a.get("description", ""),
            "source_images": a.get("source_images", []),
        })

    return {
        "folder": str(folder),
        "identity": char_dict.get("character_identity", "unknown"),
        "appearance": {
            "hair": hair.get("color", "unknown"),
            "eyes": face.get("eye_color", "unknown"),
        },
        "color_palette": {
            "main": palette[0] if len(palette) > 0 else "unknown",
            "secondary": palette[1] if len(palette) > 1 else "unknown",
            "accent": palette[2] if len(palette) > 2 else "unknown",
        },
        "clothing": {"style": clothing.get("description", "unknown")},
        "accessories": accessories,
        "signature_accessories": char_dict.get("signature_accessories", []),
        "visual_style": char_dict.get("visual_style", "unknown"),
        "source": source,
        "note": "generated by character semantic memory pipeline",
    }


def generate_character_memory(folder: str, client=None) -> dict:
    """生成并保存角色语义记忆（规格 §5.1 / §5.2）。

    - client 可用 -> VLM 路径（character_parser.parse_character_with_vlm）
    - client 为 None / 不可用 -> offline 兜底（parse_character_offline）
    - 写入 output/semantic/{folder}_character_memory.json（UTF-8、indent=2）
    - 角色文件夹不存在时抛异常（fail fast，指明路径）
    """
    folder_dir = os.path.join(config.DATASET_DIR, str(folder))
    if not os.path.isdir(folder_dir):
        raise FileNotFoundError(f"[semantic_memory] 角色文件夹不存在: {folder_dir}")
    captions = load_captions(os.path.join(folder_dir, "captions.txt"))

    if client is not None and getattr(client, "available", False):
        char_dict = character_parser.parse_character_with_vlm(client, folder_dir, captions)
        source = "vlm"
    else:
        print(f"[semantic_memory] 提示: 无可用 VLM（client={client}），使用 offline 解析")
        char_dict = character_parser.parse_character_offline(captions)
        source = "offline"

    memory = _merge_into_memory(folder, char_dict, source)

    out_path = os.path.join(config.SEMANTIC_DIR, f"{folder}_character_memory.json")
    os.makedirs(config.SEMANTIC_DIR, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(memory, f, ensure_ascii=False, indent=2)
    print(f"[semantic_memory] 已写入角色语义记忆: {out_path}")
    return memory


def load_character_memory(folder: str, client=None) -> dict:
    """读取角色语义记忆（规格 §5.2 / §27 失败回退）。

    - output/semantic/{folder}_character_memory.json 已存在 -> 直接读取（不重复生成）
    - 不存在 -> 调用 generate_character_memory 生成
    - 读取/生成全部失败 -> get_default_memory 兜底
    - 不修改原始数据集（只读 dataset/，仅写 output/semantic/）
    """
    card = config.get_character_card(folder)
    if card:
        # Every consumer sees the same reviewed semantics; keep old cache as evidence.
        return memory_from_card(folder, card)
    path = os.path.join(config.SEMANTIC_DIR, f"{folder}_character_memory.json")
    if os.path.isfile(path):
        try:
            with open(path, "r", encoding="utf-8") as f:
                memory = json.load(f)
            if isinstance(memory, dict):
                print(f"[semantic_memory] 直接读取已有记忆（不重复生成）: {path}")
                return memory
            print(f"[semantic_memory] 告警: {path} 内容不是 dict，重新生成")
        except Exception as e:
            print(f"[semantic_memory] 告警: {path} 读取失败（{type(e).__name__}: {e}），重新生成")

    try:
        return generate_character_memory(folder, client)
    except Exception as e:
        print(f"[semantic_memory] 告警: 角色语义记忆生成失败（{type(e).__name__}: {e}），"
              f"回退 get_default_memory")
        return get_default_memory(folder)


def style_policy_for_subject(card, subject):
    """Allow human character rendering without changing animal/object materials."""
    card = card or {}
    if (subject or {}).get("subject_type") == "human":
        return card.get("human_style_policy", card.get("style_policy", "preserve"))
    return card.get("style_policy", "preserve")


def memory_from_card(folder, card):
    palette = list(card.get("palette") or [])
    return {
        "folder": str(folder), "identity": str(folder), "source": "reviewed_card",
        "appearance": {"description": card.get("identity_tags", "")},
        "color_palette": dict(zip(("main", "secondary", "accent"), palette)),
        "accessories": [dict(card.get("accessory") or {})] +
                       list(card.get("secondary_accessories") or []),
        "visual_style": card.get("style", "unknown"),
        "style_policy": card.get("style_policy", "preserve"),
    }


def card_from_memory(memory):
    """Unreviewed characters use the same constrained prompt path, without 37 defaults."""
    appearance = memory.get("appearance") or {}
    identity = []
    for key in ("hair", "eyes"):
        value = appearance.get(key)
        if isinstance(value, str) and value.strip().lower() not in {"", "unknown"}:
            identity.append(value if key in value.lower() else f"{value} {key}")
    accessories = memory.get("accessories") or memory.get("signature_accessories") or []
    acc = next((dict(a) for a in accessories if isinstance(a, dict)), {})
    if not acc.get("description"):
        acc["description"] = ", ".join(str(acc[k]) for k in ("name", "shape", "color")
                                          if acc.get(k) and acc[k] != "unknown")
    return {"core_identity_tags": ", ".join(identity), "identity_tags": ", ".join(identity),
            "accessory": acc, "style_policy": "preserve", "quality_tags": "best quality",
            "palette": [v for v in (memory.get("color_palette") or {}).values()
                        if known_text(v)],
            "source": memory.get("source", "unverified")}


